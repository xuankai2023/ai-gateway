// Package stream 🔴 New API 借鉴：SSE 流式引擎（三协程 + 主循环）
//
// 参考：New API relay/helper/stream_scanner.go（约 316 行，所有渠道共用这一个入口）
//
// ============================================================================
// 流式请求是 AI 网关最容易出事的地方
// ============================================================================
// 关键边界：
//   上游返回 200 + SSE 响应头 → 客户端已经收到 200 状态码
//   → 中途断流再也不可能重试（HTTP 响应已提交，无法重发）
//   → 只能记录 EndReason 按已收数据结算
//
// 重试和流式的分水岭：
//   200 之前：可以重试换渠道（客户端还没收到任何字节）
//   200 之后：进入 SSE 引擎，断流 → 停止烧钱 + 记 EndReason
//
// ============================================================================
// 引擎结构：三协程 + 一个主循环（🔴 New API 核心设计）
// ============================================================================
//
//   ┌─ dataHandler  ─── 上游 SSE 帧 → 翻译成客户端格式 → 写回
//   ├─ keepalive    ─── 30s 定时空注释帧（防止 nginx / ALB 断长连接）
//   └─ cleanup      ─── sync.Once 幂等清理（wg.Wait 等全部退出）
//
//   主循环：
//     监听客户端 ctx.Done() ──→ 立即 close(upstreamResp.Body)
//     ↑ 🔴 断开即止损！不为已放弃的请求继续烧钱烧 token
//
// ============================================================================
// 5 个关键防御设计（New API 源码逐行验证）
// ============================================================================
// 1. 断开即止损：主循环监听 ctx.Done() → close(upstreamResp.Body)
//    长连接 + 计费场景下最重要的止损设计
//
// 2. 每帧写超时：DataHandler 每次写回前 ExtendWriteDeadline(30s)
//    慢客户端拖不死协程
//
// 3. 写锁是请求内的：writeMutex 是函数局部变量
//    只防止 ping 与 dataHandler 交叉写同一个 ResponseWriter
//    跨请求之间没有共享锁
//
// 4. 协程回收严谨：cleanup 用 sync.Once 保证幂等
//    wg.Wait() 等三个协程全部退出后才把 gin.Context 归还连接池
//    防止协程引用被复用的 Context 产生串号写
//
// 5. panic 全覆盖：三个协程都带 recover 并把原因写进 StreamStatus
//    9 种 EndReason：clean / timeout / upstream_err / client_disconnect / write_error / panic / canceled / eof / other
//    供计费与日志复盘
//
// ============================================================================
// 适配器只需传进来一个闭包（New API 适配器模式延伸）
// ============================================================================
// 每个渠道只传：convertFunc(respChunk) -> clientChunk
// 引擎统一处理并发、超时、保活、断开这些通用难题
// 新接一个渠道的流式支持 = 写一个闭包，不改引擎一行代码
